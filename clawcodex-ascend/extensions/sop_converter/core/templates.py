"""Templates for SOP conversion output.

These templates define the structure of generated Agent and Skill files.
They are used by AgentBuilder and SkillGrouper to produce the actual content.
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass
class MappingRule:
    """A mapping rule: SDK method pattern → tool name → skill name.

    Config-layer variant of ``runtime.skill_grouper.MappingRule``:
    ``match_type`` / ``match_target`` are plain strings ("substring",
    "prefix", "suffix", "regex", "exact" / "op_name", "comp_name",
    "file_path").  ``matches()`` / ``match_against()`` mirror the runtime
    class so rules constructed from either import path work inside
    SkillGrouper (``_static_group`` / ``_keyword_match_group``).
    """

    method_pattern: str
    tool_name: str
    skill_name: str
    description: str = ""
    match_type: str = "substring"
    match_target: str = "op_name"

    def matches(self, name: str) -> bool:
        if self.match_type == "prefix":
            return name.startswith(self.method_pattern)
        elif self.match_type == "suffix":
            return name.endswith(self.method_pattern)
        elif self.match_type == "regex":
            return bool(re.search(self.method_pattern, name))
        elif self.match_type == "exact":
            return name == self.method_pattern
        return self.method_pattern in name

    def match_against(self, op_name: str, comp_name: str, file_path: str) -> bool:
        """Match against the field selected by match_target."""
        if self.match_target == "comp_name":
            return self.matches(comp_name)
        elif self.match_target == "file_path":
            return self.matches(file_path)
        return self.matches(op_name)


