"""Trusted host identity helpers for the Task-v2 LKB adapter."""

from __future__ import annotations

import uuid
from typing import Any

_SELF_OWNER_SENTINEL = "$self"


def _actor(context: Any) -> str:
    """Return the best available trusted actor identity from the context."""
    for attr in ("agent_id", "actor", "session_id"):
        val = getattr(context, attr, None)
        if isinstance(val, str) and val:
            return val
    return "agent"


def resolve_task_owner(tool_input: dict[str, Any], context: Any) -> dict[str, Any]:
    """Resolve the model-safe self-owner sentinel at the trusted host boundary.

    Models do not know the opaque ToolContext agent id generated by the host.
    Requiring them to copy it made ordinary claims look like third-party
    transfers. The host therefore replaces the self sentinel with the trusted
    actor before hashing, validation, or native Task-v2 fallback handling.
    """
    owner = tool_input.get("owner")
    if not isinstance(owner, str) or owner.strip().casefold() != _SELF_OWNER_SENTINEL:
        return tool_input
    return {**tool_input, "owner": _actor(context)}


def _actor_roles(context: Any) -> tuple[str, ...]:
    """Return host-asserted roles without consulting model-controlled input."""
    raw = getattr(context, "actor_roles", ())
    if not isinstance(raw, (list, tuple)):
        return ()
    return tuple(dict.fromkeys(role.strip() for role in raw if isinstance(role, str) and role.strip()))


def _idempotency_key(context: Any, tool_input: dict[str, Any]) -> str | None:
    """Return the explicit request identity or the ToolContext tool-use id."""
    for key in ("idempotency_key", "request_id"):
        val = tool_input.get(key)
        if isinstance(val, str) and val.strip():
            return val.strip()
    tool_use_id = getattr(context, "tool_use_id", None)
    if isinstance(tool_use_id, str) and tool_use_id:
        return tool_use_id
    return None


def _command_id(
    context: Any,
    tool_name: str,
    tool_input: dict[str, Any],
    *,
    plan_id: str,
) -> str:
    """Build a stable command id when a request identity is available.

    Explicit request keys and the host tool-use id make retries idempotent.
    Compatibility callers without either receive a collision-safe, single-use
    fallback because the host has no identity with which to correlate retries.
    """
    key = _idempotency_key(context, tool_input)
    if key:
        return f"host-{plan_id}-{tool_name.lower()}-{key}"
    return f"host-{plan_id}-{tool_name.lower()}-{uuid.uuid4().hex[:8]}"


def _task_id_of(tool_input: dict[str, Any]) -> str:
    """Read the task id from either snake_case or camelCase input."""
    return str(tool_input.get("task_id") or tool_input.get("taskId") or "")


def _metadata_type_error(tool_input: dict[str, Any]) -> str | None:
    """Reject metadata shapes that would corrupt the Task-v2 projection."""
    metadata = tool_input.get("metadata")
    if metadata is None:
        return None
    if not isinstance(metadata, dict):
        return "metadata must be an object when provided"
    if "owner" in metadata:
        return (
            "metadata.owner is reserved and never changes task ownership; use top-level owner='$self' to claim the task"
        )
    lkb_meta = metadata.get("lkb")
    if lkb_meta is not None and not isinstance(lkb_meta, dict):
        return "metadata.lkb must be an object when provided"
    return None
